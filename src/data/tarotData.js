// Helper to fetch from TarotAPI or fallback safely
export async function getDailyTarotCard() {
  try {
    // Try public tarot api
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 3000);
    
    const response = await fetch('https://tarotapi.dev/api/v1/cards/random?n=1', {
      signal: controller.signal
    });
    clearTimeout(timeoutId);

    if (response.ok) {
      const data = await response.json();
      if (data && data.cards && data.cards.length > 0) {
        const apiCard = data.cards[0];
        // Match with our rich Thai dataset if possible
        const matched = TAROT_DECK.find(c => 
          c.name.toLowerCase() === apiCard.name.toLowerCase() ||
          c.id.toLowerCase() === (apiCard.name_short || '').toLowerCase()
        );

        if (matched) {
          return {
            ...matched,
            meaning_up: apiCard.meaning_up || matched.meaning,
          };
        } else {
          // Construct fallback card from API
          return {
            id: apiCard.name_short || 'custom',
            name: apiCard.name,
            nameTh: apiCard.name,
            arcana: apiCard.type || 'Tarot',
            image: `https://upload.wikimedia.org/wikipedia/commons/thumb/9/90/RWS_Tarot_00_Fool.jpg/300px-RWS_Tarot_00_Fool.jpg`,
            keywords: [apiCard.meaning_up ? apiCard.meaning_up.split(',')[0] : 'ความโชคดี'],
            meaning: apiCard.meaning_up || 'วันนี้เป็นวันที่ดีและราบรื่น มีพลังบวกพร้อมเริ่มสิ่งใหม่',
            advice: 'ก้าวไปข้างหน้าด้วยความมั่นใจและรอยยิ้ม',
            energy: '✨ พลังบวกเสริมความมั่นใจในการทำงาน'
          };
        }
      }
    }
  } catch (error) {
    console.log('Using built-in tarot dataset:', error.message);
  }

  // Fallback to our rich local dataset
  const randomIndex = Math.floor(Math.random() * TAROT_DECK.length);
  return TAROT_DECK[randomIndex];
}
